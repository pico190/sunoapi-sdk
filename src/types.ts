/**
 * Complete type definitions for the SunoAPI SDK.
 *
 * All request/response shapes are derived from the published OpenAPI specs
 * (suno-api.json, suno-voice-api.json, file-upload-api.json) published at
 * https://docs.sunoapi.org.
 *
 * Two different response envelopes exist:
 *  - The **main** and **voice** APIs wrap results in `{ code, msg, data }`.
 *  - The **file upload** API wraps results in `{ success, code, msg, data }`.
 *
 * This SDK transparently unwraps the `data` field for you, so every method
 * returns the inner payload directly.
 */

