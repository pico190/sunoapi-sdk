/**
 * Envelope returned by the main & voice APIs.
 * The SDK unwraps `data` for you — you normally never see this object.
 */
export interface ApiResponse<T> {
  /** `200` indicates success; any other value is an error. */
  code: number;
  /** Human readable message. */
  msg: string;
  /** The actual payload. */
  data: T;
}

/**
 * Envelope returned by the file-upload API (note the `success` boolean).
 */
export interface UploadApiResponse<T> {
  success: boolean;
  code: number;
  msg: string;
  data: T;
}

