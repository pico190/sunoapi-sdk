/**
 * A single generated track as returned inside a music record-info response.
 *
 * > Note: record-info responses use **camelCase** (`audioUrl`), while the
 * > asynchronous callback payloads use **snake_case** (`audio_url`). This SDK
 * > models the record-info shape.
 */
export interface AudioTrack {
  /** Unique track id (use with extend / wav / midi / video / persona). */
  id: string;
  /** Direct download URL of the generated audio. */
  audioUrl: string;
  /** Streamable audio URL. */
  streamAudioUrl: string;
  /** Cover art URL. */
  imageUrl: string;
  /** The prompt that produced this track. */
  prompt: string;
  /** Model name that generated the track. */
  modelName: string;
  /** Track title. */
  title: string;
  /** Comma separated style tags. */
  tags: string;
  /** Creation timestamp (ISO string). */
  createTime: string;
  /** Duration in seconds. */
  duration: number;
}

/**
 * A single lyrics item returned inside a lyrics record-info response.
 */
export interface LyricsItem {
  /** The generated lyrics text. */
  text: string;
  /** Title of the lyrics. */
  title: string;
  /** Status of the lyrics item. */
  status: string;
  /** Error message if generation failed. */
  errorMessage: string;
}

/**
 * One word-aligned lyric token (used by the timestamped-lyrics endpoint).
 */
export interface AlignedWord {
  word: string;
  success: boolean;
  /** Start time in seconds. */
  startS: number;
  /** End time in seconds. */
  endS: number;
  palign: number;
}

/**
 * One separated instrument stem.
 */
export interface OriginData {
  /** Duration in seconds. */
  duration: number;
  /** Download URL of this stem. */
  audio_url: string;
  /** Group / instrument name of this stem. */
  stem_type_group_name: string;
  /** Stem id. */
  id: string;
}

/**
 * A single MIDI instrument and its notes.
 */
export interface MidiInstrument {
  /** Instrument name. */
  name: string;
  /** Note events for this instrument. */
  notes: MidiNote[];
}

/**
 * A single MIDI note event.
 */
export interface MidiNote {
  /** MIDI pitch (0-127). */
  pitch: number;
  /** Start time in seconds. */
  start: number;
  /** End time in seconds. */
  end: number;
  /** Velocity (0-127). */
  velocity: number;
}

