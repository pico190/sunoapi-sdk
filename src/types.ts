/** Common advanced controls shared by most music endpoints. */
export interface AdvancedMusicControls {
  /** Persona id to apply (optional). */
  personaId?: string;
  /** Persona model type when using `personaId`. @default 'style_persona' */
  personaModel?: PersonaModel;
  /** Styles to avoid (e.g. "Heavy Metal, Upbeat Drums"). */
  negativeTags?: string;
  /** Preferred vocal gender. */
  vocalGender?: VocalGender;
  /** Style adherence weight, 0.00–1.00. */
  styleWeight?: number;
  /** Creativity / novelty constraint, 0.00–1.00. */
  weirdnessConstraint?: number;
  /** Input-audio influence weight, 0.00–1.00. */
  audioWeight?: number;
}

/** Parameters accepted by every music generation request. */
export interface GenerateMusicParams extends AdvancedMusicControls {
  /**
   * Custom Mode enables advanced controls (`style` + `title` required;
   * `prompt` required when `instrumental` is `false`).
   */
  customMode: boolean;
  /** `true` = instrumental (no lyrics). */
  instrumental: boolean;
  /** Model version. */
  model: SongGenerationModel;
  /** Callback URL for completion notifications. */
  callBackUrl: string;
  /**
   * Description of the desired audio. Required in Custom Mode when
   * `instrumental` is `false`.
   */
  prompt?: string;
  /** Music style / genre. Required in Custom Mode. */
  style?: string;
  /** Track title. Required in Custom Mode. */
  title?: string;
  /**
   * Duration in seconds (10–360). Only effective when `model` is `V5_5`
   * and `customMode` is `true`. Must be an integer.
   */
  duration?: number;
}

/** Parameters for extending an existing track. */
export interface ExtendMusicParams extends AdvancedMusicControls {
  /**
   * `true` = use custom parameters (`continueAt`, `style`, `title` required;
   * `prompt` required when `instrumental` is `false`).
   */
  defaultParamFlag: boolean;
  /** Audio id of the track to extend. */
  audioId: string;
  /** Callback URL for completion notifications. */
  callBackUrl: string;
  /** Model version (must match the source track). */
  model: SongGenerationModel;
  /** `true` = instrumental. If `true`, `prompt` / `vocalGender` must be omitted. */
  instrumental?: boolean;
  /** Description of how to extend. Required when custom params & not instrumental. */
  prompt?: string;
  /** Music style, e.g. "Jazz". */
  style?: string;
  /** Music title. */
  title?: string;
  /** Start time (seconds) to begin the extension. Required in custom mode. */
  continueAt?: number;
}

/** Parameters for cover generation from an uploaded audio file. */
export interface UploadCoverParams extends GenerateMusicParams {
  /** URL of the uploaded audio (max 8 minutes). Required in all modes. */
  uploadUrl: string;
}

/** Parameters for extending from an uploaded audio file. */
export interface UploadExtendParams extends AdvancedMusicControls {
  /** URL of the uploaded audio (max 8 minutes). Required in all modes. */
  uploadUrl: string;
  /** Custom parameter mode toggle. */
  defaultParamFlag: boolean;
  /** Model version (must match the source audio). */
  model: SongGenerationModel;
  /** Callback URL. */
  callBackUrl: string;
  /** `true` = instrumental. */
  instrumental?: boolean;
  /** Extension description (optional in all cases). */
  prompt?: string;
  /** Music style. Required when `defaultParamFlag` is `true`. */
  style?: string;
  /** Music title. Required when `defaultParamFlag` is `true`. */
  title?: string;
  /** Start time (seconds) to begin the extension. Required in custom mode. */
  continueAt?: number;
  /** Duration (seconds), only when custom mode & `V5_5`. */
  duration?: number;
}

/** Parameters for a mashup of exactly two uploaded tracks. */
export interface MashupParams extends AdvancedMusicControls {
  /** Exactly 2 accessible audio URLs to mash up. */
  uploadUrlList: string[];
  /** Custom Mode toggle. */
  customMode: boolean;
  /** Model version. */
  model: SongGenerationModel;
  /** Callback URL. */
  callBackUrl: string;
  /** Description of the desired audio. */
  prompt?: string;
  /** Music style / genre. Required in Custom Mode. */
  style?: string;
  /** Track title. Required in Custom Mode. */
  title?: string;
  /** `true` = instrumental. */
  instrumental?: boolean;
  /** Duration (seconds), only when custom mode & `V5_5`. */
  duration?: number;
}

