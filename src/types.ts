/**
 * Available music generation models.
 *
 * - `V5_5` — "Unleash Your Voice": custom models tailored to your unique taste.
 * - `V5`   — latest general model.
 * - `V4_5ALL`, `V4_5PLUS`, `V4_5`, `V4` — progressively older generations.
 *
 * Some features (e.g. `duration`) are only supported on specific models.
 */
export type SongGenerationModel =
  | 'V4'
  | 'V4_5'
  | 'V4_5PLUS'
  | 'V4_5ALL'
  | 'V5'
  | 'V5_5';

